const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');
const root = path.join(__dirname,'..');
const output = path.join(root,'_site');
const html = p=>fs.readFileSync(path.join(output,p,'index.html'),'utf8');
test('Eleventy builds both languages and all four page types without third-party assets', () => {
  execFileSync('npm',['run','build'],{cwd:root,stdio:'pipe'});
  for (const p of ['no/','en/','no/om/','en/about/','no/kategori/konsert/','en/category/concert/','no/hendelse/2027-01-09-fiktiv-lyskveld/','en/event/2027-01-09-fiktiv-lyskveld/']) assert.match(html(p),/<html lang="(no|en)"/);
  assert.match(html('no/'),/<meta name="robots" content="noindex,nofollow">/);
  assert.match(html('no/'),/FIKTIVT EKSEMPEL/);
  assert.match(html('en/'),/FICTIONAL EXAMPLE/);
  assert.match(html('no/'),/data-time-filter="today"/);
  assert.match(html('no/'),/href="\/en\/" lang="en"/);
  assert.match(html('no/'),/data-filter-list/);
  assert.match(html(''),/href="\/no\/"/);
  assert.match(html('no/'),/class="empty-art" src="\/assets\/quiet-waters.webp"/);
  assert.match(html('no/'),/<noscript>/);
  assert.doesNotMatch(html('no/'),/https?:\/\/(fonts|www\.google|unpkg|cdn\.)/);
  assert.doesNotMatch(html('en/event/2027-01-09-fiktiv-lyskveld/'),/Tickets and more information/);
  assert.equal(fs.readdirSync(path.join(root,'events')).filter(x=>x.endsWith('.json')).length,8);
  assert.equal(fs.readdirSync(path.join(output,'images')).filter(x=>x.endsWith('.webp')).length,8);
  assert.equal(fs.readdirSync(path.join(output,'images/cards')).filter(x=>x.endsWith('.webp')).length,8);
  assert.match(html('no/'),/src="\/images\/cards\/2026-11-06-fiktiv-havnemelodi.webp"/);
});
